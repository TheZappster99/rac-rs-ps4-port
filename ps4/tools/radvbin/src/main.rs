//! radvbin OUTDIR BLOB...: each radv pipeline-binary blob (one compiled shader stage, from `vkc` with VKC_DUMP) becomes
//! OUTDIR/<blob name>.rsh, the PS4 shader-cache entry format below, after checks that it is what this tool understands.
//!
//! The blob is radv's `radv_shader_binary_legacy` (Mesa 26.1.6): `ac_shader_config` (register counts, RSRC1/2/3, PS input
//! enables, scratch), `radv_shader_info` (user SGPR locations of the descriptor sets and other user data, the VS output
//! parameter map, PS inputs and colour export format, ...), then statistics and the GCN machine code. Field offsets come from
//! layout.rs, generated by layout.c from the exact Mesa structs.
//!
//! .rsh (little-endian u32 words unless noted), version 1:
//!   0  magic "RSH1"            1  stage (0 vertex, 1 fragment, 2 compute)
//!   2  num_sgprs   3 num_vgprs  4 scratch_bytes_per_wave  5 float_mode  6 lds_size
//!   7  rsrc1       8 rsrc2      9 rsrc3     10 user_data_0 (register of user SGPR 0)
//!   11 desc_set_used_mask      12 push_constant_size  13-14 inline_push_constant_mask (u64)
//!   15 ps spi_ps_input_ena     16 ps spi_ps_input_addr 17 ps spi_shader_col_format 18 ps cb_shader_mask
//!   19 ps num_inputs           20 ps input_mask (bit k = VAR k) 21 ps explicit (flat) mask 22 ps colors_written
//!   23 vs param_exports        24 vs clip_dist_mask | cull_dist_mask << 8 | writes_pointsize << 16
//!   25 vs vb_desc_usage_mask   26 vs num_attributes   27-29 cs block_size xyz
//!   30 code bytes (exec size)  31 reserved
//!   then 32 x (i8 sgpr, u8 count) descriptor-set user SGPRs (64 bytes), 28 x (i8, u8) other user data (56 bytes, AC_UD_*),
//!   64 bytes VS output parameter offset per varying slot (0xff = none), then the code.

mod layout;
use layout::*;

const MAGIC: &[u8; 4] = b"RSH1";
const HEADER_WORDS: usize = 32;

fn u32_at(b: &[u8], o: usize) -> u32 {
	u32::from_le_bytes(b[o..o + 4].try_into().unwrap())
}

fn u64_at(b: &[u8], o: usize) -> u64 {
	u64::from_le_bytes(b[o..o + 8].try_into().unwrap())
}

struct Parsed {
	stage: u32,
	words: [u32; HEADER_WORDS],
	ud: Vec<u8>,
	code: Vec<u8>,
}

fn parse(b: &[u8]) -> Result<Parsed, String> {
	if b.len() < LEGACY_DATA {
		return Err(format!("{} bytes, shorter than the header ({LEGACY_DATA})", b.len()));
	}
	if u32_at(b, TYPE) != 0 {
		return Err(format!("binary type {} (only legacy = 0 is understood)", u32_at(b, TYPE)));
	}
	let total = u32_at(b, TOTAL_SIZE) as usize;
	if total != b.len() {
		return Err(format!("total_size {total} but the blob has {} bytes (another Mesa version?)", b.len()));
	}
	let (code_size, exec_size, ir, disasm, stats, dbg) = (
		u32_at(b, LEGACY_CODE_SIZE) as usize,
		u32_at(b, LEGACY_EXEC_SIZE) as usize,
		u32_at(b, LEGACY_IR_SIZE) as usize,
		u32_at(b, LEGACY_DISASM_SIZE) as usize,
		u32_at(b, LEGACY_STATS_SIZE) as usize,
		u32_at(b, LEGACY_DEBUG_INFO_SIZE) as usize,
	);
	let code_at = LEGACY_DATA + stats;
	if exec_size > code_size || code_at + code_size > b.len() || ir + disasm + dbg > b.len() {
		return Err(format!("sizes do not add up: code {code_size} exec {exec_size} stats {stats} ir {ir} disasm {disasm} debug {dbg}"));
	}
	let code = b[code_at..code_at + exec_size].to_vec();
	// The program ends with s_endpgm (0xbf810000); radv pads after it for instruction prefetch, which exec_size leaves out.
	if code.len() < 4 || !code.chunks_exact(4).any(|w| u32::from_le_bytes(w.try_into().unwrap()) == 0xbf81_0000) {
		return Err("no s_endpgm in the code".into());
	}
	let ud0 = u32_at(b, INFO_USER_DATA_0);
	let stage = match ud0 {
		0xb130 => 0, // SPI_SHADER_USER_DATA_VS_0
		0xb030 => 1, // SPI_SHADER_USER_DATA_PS_0
		0xb900 => 2, // COMPUTE_USER_DATA_0
		_ => return Err(format!("user_data_0 {ud0:#x}: not a hardware VS, PS or CS (GFX7 only has those here)")),
	};
	let mut w = [0u32; HEADER_WORDS];
	w[0] = u32::from_le_bytes(*MAGIC);
	w[1] = stage;
	w[2] = u32_at(b, CONFIG_NUM_SGPRS);
	w[3] = u32_at(b, CONFIG_NUM_VGPRS);
	w[4] = u32_at(b, CONFIG_SCRATCH_BYTES_PER_WAVE);
	w[5] = u32_at(b, CONFIG_FLOAT_MODE);
	w[6] = u32_at(b, CONFIG_LDS_SIZE);
	w[7] = u32_at(b, CONFIG_RSRC1);
	w[8] = u32_at(b, CONFIG_RSRC2);
	w[9] = u32_at(b, CONFIG_RSRC3);
	w[10] = ud0;
	w[11] = u32_at(b, INFO_DESC_SET_USED_MASK);
	w[12] = u32_at(b, INFO_PUSH_CONSTANT_SIZE);
	let ipc = u64_at(b, INFO_INLINE_PUSH_CONSTANT_MASK);
	w[13] = ipc as u32;
	w[14] = (ipc >> 32) as u32;
	if stage == 1 {
		w[15] = u32_at(b, INFO_PS_SPI_PS_INPUT_ENA);
		w[16] = u32_at(b, INFO_PS_SPI_PS_INPUT_ADDR);
		w[17] = u32_at(b, INFO_PS_SPI_SHADER_COL_FORMAT);
		w[18] = u32_at(b, INFO_PS_CB_SHADER_MASK);
		w[19] = u32_at(b, INFO_PS_NUM_INPUTS);
		w[20] = u32_at(b, INFO_PS_INPUT_MASK);
		w[21] = u32_at(b, INFO_PS_EXPLICIT_SHADED_MASK);
		w[22] = u32_at(b, INFO_PS_COLORS_WRITTEN);
		// The inputs radv interpolates (32-bit, 16-bit); every other input that is neither these nor explicit is flat and
		// gets FLAT_SHADE (radv_shader.c `radv_ps_input_type_bits`). Bit 31 of word 24 says the two masks are here.
		w[23] = u32_at(b, INFO_PS_FLOAT32_SHADED_MASK);
		w[24] = u32_at(b, INFO_PS_FLOAT16_SHADED_MASK) & 0x7fff_ffff | 1 << 31;
		// The PS input enables radv put in the config and in the shader info must agree.
		if w[15] != u32_at(b, CONFIG_SPI_PS_INPUT_ENA) || w[16] != u32_at(b, CONFIG_SPI_PS_INPUT_ADDR) {
			return Err("PS input enables differ between config and info (layout mismatch?)".into());
		}
		if w[19] != w[20].count_ones() {
			return Err(format!("PS num_inputs {} but input_mask {:#x} (layout mismatch?)", w[19], w[20]));
		}
	}
	if stage == 0 {
		w[23] = b[INFO_PARAM_EXPORTS] as u32;
		w[24] = b[INFO_CLIP_DIST_MASK] as u32 | (b[INFO_CULL_DIST_MASK] as u32) << 8 | (b[INFO_WRITES_POINTSIZE] as u32) << 16;
		w[25] = u32_at(b, INFO_VS_VB_DESC_USAGE_MASK);
		w[26] = b[INFO_VS_NUM_ATTRIBUTES] as u32;
	}
	if stage == 2 {
		for i in 0..3 {
			w[27 + i] = u32_at(b, INFO_CS_BLOCK_SIZE + 4 * i);
		}
		if w[27] * w[28] * w[29] != u32_at(b, INFO_WORKGROUP_SIZE) {
			return Err("compute block size and workgroup size disagree (layout mismatch?)".into());
		}
	}
	w[30] = code.len() as u32;
	// RSRC2.USER_SGPR (bits 1-5) must cover every user SGPR the info places.
	let user_sgprs = (w[8] >> 1) & 0x1f;
	let mut ud = Vec::with_capacity(184);
	ud.extend_from_slice(&b[INFO_UD_DESCRIPTOR_SETS..INFO_UD_DESCRIPTOR_SETS + 2 * 32]);
	ud.extend_from_slice(&b[INFO_UD_SHADER_DATA..INFO_UD_SHADER_DATA + 2 * AC_UD_MAX]);
	for e in ud.chunks_exact(2) {
		let (idx, n) = (e[0] as i8, e[1] as u32);
		if idx >= 0 && idx as u32 + n > user_sgprs {
			return Err(format!("user data at SGPR {idx} (+{n}) past RSRC2.USER_SGPR {user_sgprs}"));
		}
	}
	let po = if stage == 0 { &b[INFO_VS_OUTPUT_PARAM_OFFSET..INFO_VS_OUTPUT_PARAM_OFFSET + VARYING_SLOT_MAX] } else { &[0xffu8; VARYING_SLOT_MAX][..] };
	ud.extend_from_slice(po);
	Ok(Parsed { stage, words: w, ud, code })
}

const UD_NAMES: [&str; 28] = [
	"scratch_ring_offsets", "push_constants", "inline_push_constants", "indirect_descriptors", "view_index", "streamout_buffers",
	"streamout_state", "task_state", "nggc_settings", "nggc_viewport", "ngg_lds_layout", "ngg_state", "ngg_query_buf_va",
	"vgt_esgs_ring_itemsize", "force_vrs_rates", "task_ring_entry", "next_stage_pc", "epilog_pc", "dynamic_descriptors",
	"dynamic_descriptors_offset_addr", "stage_0 (vs: vertex_buffers, cs: grid_size)", "stage_1 (vs: base_vertex_start_instance)",
	"stage_2 (vs: prolog_inputs)", "stage_3", "stage_4 (ps: ps_state)", "stage_5", "stage_6", "stage_7",
];

fn main() {
	let a: Vec<String> = std::env::args().skip(1).collect();
	if a.len() < 2 {
		eprintln!("usage: radvbin OUTDIR BLOB...");
		std::process::exit(2);
	}
	let out = &a[0];
	std::fs::create_dir_all(out).unwrap();
	let mut bad = 0;
	for path in &a[1..] {
		let b = std::fs::read(path).expect("read blob");
		let name = std::path::Path::new(path).file_stem().unwrap().to_string_lossy().into_owned();
		match parse(&b) {
			Ok(p) => {
				let w = &p.words;
				let stage = ["vertex", "fragment", "compute"][p.stage as usize];
				println!("{name}: {stage}, {} B code, {} SGPRs {} VGPRs, scratch {} B/wave, rsrc1 {:#010x} rsrc2 {:#010x}, sets used {:#x}, push constants {} B (inline mask {:#x})",
					w[30], w[2], w[3], w[4], w[7], w[8], w[11], w[12], (w[14] as u64) << 32 | w[13] as u64);
				for (i, e) in p.ud[..64].chunks_exact(2).enumerate() {
					if (e[0] as i8) >= 0 {
						println!("    set {i}: user SGPR {} (+{})", e[0], e[1]);
					}
				}
				for (i, e) in p.ud[64..64 + 2 * AC_UD_MAX].chunks_exact(2).enumerate() {
					if (e[0] as i8) >= 0 {
						println!("    {}: user SGPR {} (+{})", UD_NAMES[i], e[0], e[1]);
					}
				}
				match p.stage {
					0 => {
						let po = &p.ud[64 + 2 * AC_UD_MAX..];
						let vars: Vec<String> = (0..32).filter(|&k| po[32 + k] != 0xff).map(|k| format!("VAR{k}->{}", po[32 + k])).collect();
						println!("    params {}, vertex buffer descriptors used {:#x}, attributes {}, outputs [{}]", w[23], w[25], w[26], vars.join(" "));
					}
					1 => println!("    ps_input_ena {:#x} addr {:#x}, col_format {:#x}, cb_shader_mask {:#x}, inputs {} (mask {:#x}, explicit {:#x}, float32 {:#x}, float16 {:#x}), colors {:#x}", w[15], w[16], w[17], w[18], w[19], w[20], w[21], w[23], w[24] & 0x7fff_ffff, w[22]),
					_ => println!("    block {}x{}x{}", w[27], w[28], w[29]),
				}
				let mut f = Vec::with_capacity(HEADER_WORDS * 4 + p.ud.len() + p.code.len());
				for x in w {
					f.extend_from_slice(&x.to_le_bytes());
				}
				f.extend_from_slice(&p.ud);
				f.extend_from_slice(&p.code);
				std::fs::write(format!("{out}/{name}.rsh"), f).unwrap();
			}
			Err(e) => {
				bad += 1;
				println!("{name}: REFUSED: {e}");
			}
		}
	}
	if bad > 0 {
		std::process::exit(1);
	}
}
